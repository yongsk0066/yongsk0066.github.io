"""Bake the calendar stock. Run with: uv run --with numpy scripts/bake-calendar-paper.py"""

import base64
import json
from pathlib import Path
import textwrap

import numpy as np


# Newsprint, Lee et al. (2023), tables 2 and 4.
# https://www.ktappi.kr/articles/xml/8111/
TARGET = np.array([6.911, 86.239, 6.825])
RA_MM = 2.24e-3
TILE_MM = 12.5
SAMPLES = 1024
SIZE = 128
TARGET /= TARGET.sum()


def surface_slopes():
    freq = np.fft.fftfreq(SAMPLES, d=TILE_MM / SAMPLES)
    k = np.abs(freq)
    # Profile wavelengths 1–10, 0.1–1 and the resolved part of 0.01–0.1 mm.
    band = np.digitize(k, [1., 10.])
    rng = np.random.default_rng(0x766A1573)
    spectrum = np.fft.fft2(rng.standard_normal((SAMPLES, SAMPLES)))
    radius2 = freq[:, None]**2 + freq[None, :]**2
    spectrum *= (1 + radius2)**-.7
    for i in [0, SAMPLES // 2, 1, -1]:
        spectrum[i, :] = 0
        spectrum[:, i] = 0

    # Constrain the measured 1-D height powers. The other axis uses the same
    # target because this paper has no cross-direction measurement.
    cells = 3 * band[:, None] + band[None, :]
    power = np.bincount(cells.ravel(), weights=np.abs(spectrum).ravel()**2).reshape(3, 3)
    target = TARGET * power.sum()
    fitted = power.copy()
    for _ in range(40):
        fitted *= target / fitted.sum(axis=0)
        fitted *= (target / fitted.sum(axis=1))[:, None]
    spectrum *= np.sqrt(fitted / power).ravel()[cells]
    height = np.fft.ifft2(spectrum).real
    spectrum *= RA_MM / np.abs(height).mean()
    height = np.fft.ifft2(spectrum).real
    dx = np.fft.ifft2(spectrum * (2j * np.pi * freq[None, :])).real
    dy = np.fft.ifft2(spectrum * (2j * np.pi * freq[:, None])).real
    # Average the first AND second moments over the footprint, including
    # structure finer than level zero. This is an isotropic LEAN approximation.
    stride = SAMPLES // SIZE
    box = lambda a: a.reshape(SIZE, stride, SIZE, stride).mean(axis=(1, 3))
    powers = np.abs(spectrum)**2
    md = np.bincount(band, weights=powers.sum(axis=0))
    stats = {"reference_resolution": SAMPLES, "tile_mm": TILE_MM,
             "Ra_um": float(abs(height).mean()*1000), "height_power_percent": (md*100/md.sum()).tolist(),
             "surface_slope_rms": float(np.sqrt((dx*dx + dy*dy).mean()))}
    return box(dx), box(dy), box(dx*dx + dy*dy), stats


def formation():
    # Fabricated, neutral, smoothly varying fibre formation. Its amplitude
    # and phase are independent of the measured surface-height spectrum.
    freq = np.fft.fftfreq(SIZE) * SIZE
    radius2 = freq[:, None]**2 + freq[None, :]**2
    window = (1 - np.exp(-radius2 / 20)) * np.exp(-radius2 / 1300)
    spectrum = np.fft.fft2(np.random.default_rng(0x75CA4E1D).standard_normal((SIZE, SIZE)))
    field = np.fft.ifft2(spectrum * window).real
    field -= field.mean()
    return field / np.abs(field).max() * .99


if __name__ == "__main__":
    dx, dy, square, stats = surface_slopes()
    # The scale bounds both signed means and second moments at every level.
    scale = float(np.ceil(20 * np.sqrt(square.max())) / 20)
    field = np.stack([formation(), dx/scale, dy/scale, square/scale**2], axis=-1)
    byte_levels = []
    for level in range(SIZE.bit_length()):
        encoded = np.rint(field * [127, 127, 127, 255] + [128, 128, 128, 0])
        assert encoded.min() >= 0 and encoded.max() <= 255
        byte_levels.append(encoded.astype(np.uint8).tobytes())
        if field.shape[0] > 1:
            half = field.shape[0] // 2
            field = field.reshape(half, 2, half, 2, 4).mean(axis=(1, 3))
    assert list(byte_levels[-1][:3]) == [128, 128, 128]
    # Each component differs from the rounded average of its four quantised
    # parent texels by at most one. Keep all four signed residuals in one byte.
    packed = [byte_levels[0]]
    previous = np.frombuffer(byte_levels[0], dtype=np.uint8).reshape(SIZE, SIZE, 4)
    for mip in byte_levels[1:]:
        width = previous.shape[0] // 2
        current = np.frombuffer(mip, dtype=np.uint8).reshape(width, width, 4)
        average = (previous.reshape(width, 2, width, 2, 4).sum(axis=(1, 3)) + 2) // 4
        delta = current.astype(int) - average.astype(int)
        assert np.abs(delta).max() <= 1
        groups = ((delta + 1) << np.array([0, 2, 4, 6])).sum(axis=2)
        packed.append(groups.astype(np.uint8).tobytes())
        previous = current
    encoded = base64.b64encode(b"".join(packed)).decode()
    target_path = Path(__file__).resolve().parents[1] / "src/components/calendar/textures/paper-stock-data.ts"
    target_path.write_text(
        "// Generated by scripts/bake-calendar-paper.py. Base RGBA8 plus lossless mip residuals.\n"
        + f"export const paperSlopeScale = {scale};\n"
        + f"export const paperMeanSlopePower = {float(square.mean()):.5f};\nexport default `\n"
        + "\n".join(textwrap.wrap(encoded, width=128)) + "\n`;\n"
    )
    stats.update({"slope_scale": scale, "mip_bytes": sum(map(len, byte_levels)),
                  "packed_bytes": sum(map(len, packed)),
                  "resolved_slope_rms_at_base": float(np.sqrt((dx*dx+dy*dy).mean()))})
    print(json.dumps(stats, indent=2))
